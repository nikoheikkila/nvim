-- Pure logic behind `:Update` (config/updater.lua): CalVer comparison, release
-- URL parsing, the startup-check throttle, and which files survive an update.
-- Free of vim calls so it stays unit-testable under plain busted.
local yaml_utils = require("lib.yaml_utils")

local M = {}

-- Files the user edits to configure the editor. An update never replaces them:
-- the user's copy is carried into the new release, and the release copy is used
-- only when the user has none. Add a new user-editable root file here, or every
-- `:Update` silently resets it.
M.USER_FILES = { "config.yml", "theme.yml", ".vale.ini", ".markdownlint.jsonc" }

-- config.yml `config.updates.*`.
M.DEFAULTS = {
  checkOnStartup = true,
}

-- Seconds between two background update checks.
M.CHECK_INTERVAL = 24 * 60 * 60

---Release tags are CalVer, `YYYY.MM.DD` with an optional same-day counter
---(`2026.11.03.1`), as cut by the package job in .github/workflows/ci.yml.
---@param tag any
---@return integer[]|nil { year, month, day, counter }, nil when malformed
function M.parse(tag)
  if type(tag) ~= "string" then
    return nil
  end
  local y, m, d, rest = tag:match("^(%d%d%d%d)%.(%d%d)%.(%d%d)(.*)$")
  if not y then
    return nil
  end
  local n = 0
  if rest ~= "" then
    local counter = rest:match("^%.(%d+)$")
    if not counter then
      return nil
    end
    n = tonumber(counter)
  end
  return { tonumber(y), tonumber(m), tonumber(d), n }
end

---Whether `latest` should replace `installed`. An installed version that does
---not parse (a missing stamp, a hand-copied config) counts as outdated, so it can
---always be updated; a `latest` that does not parse is never newer, so a
---surprising GitHub answer cannot trigger an install.
---@param latest any
---@param installed any
---@return boolean
function M.is_newer(latest, installed)
  local a = M.parse(latest)
  if not a then
    return false
  end
  local b = M.parse(installed)
  if not b then
    return true
  end
  for i = 1, 4 do
    if a[i] ~= b[i] then
      return a[i] > b[i]
    end
  end
  return false
end

---The tag at the end of the URL `releases/latest` redirects to, e.g.
---`https://github.com/<owner>/<repo>/releases/tag/2026.11.03`.
---@param url any
---@return string|nil
function M.tag_from_url(url)
  if type(url) ~= "string" then
    return nil
  end
  local tag = url:match("/releases/tag/([^/?#%s]+)%s*$")
  return M.parse(tag) and tag or nil
end

---Whether the background check is due. A missing or corrupt timestamp is due;
---so is one in the future (a clock that jumped back), which would otherwise
---silence the check until the clock caught up.
---@param last any epoch seconds of the previous check
---@param now integer epoch seconds
---@param interval integer seconds
---@return boolean
function M.should_check(last, now, interval)
  if type(last) ~= "number" or last > now then
    return true
  end
  return now - last >= interval
end

---Build the update settings from yaml_utils.parse() output (table | nil). A
---missing or wrong-typed field keeps its default.
---@return { checkOnStartup: boolean }
function M.resolve_config(parsed)
  return (yaml_utils.resolve_section(parsed, "updates", M.DEFAULTS))
end

---Where to read what changed between `from` and `to`: the compare view when
---the installed version is known, otherwise the release page.
---@param repo string owner/name
---@param from string|nil
---@param to string
---@return string
function M.changes_url(repo, from, to)
  if M.parse(from) then
    return ("https://github.com/%s/compare/%s...%s"):format(repo, from, to)
  end
  return ("https://github.com/%s/releases/tag/%s"):format(repo, to)
end

---Paths, relative to the config root, to copy from the old install into the new
---one: the user files, plus the Vale StylesPath when it lives inside the config
---root. That directory is generated by `:ValeSync` rather than shipped, and Vale
---goes silent without it. An absolute StylesPath, or one escaping the root, is
---outside the swapped directory and survives on its own.
---@param styles_path string|nil from vale_utils.styles_path
---@return string[]
function M.carry_over(styles_path)
  local paths = {}
  for _, name in ipairs(M.USER_FILES) do
    table.insert(paths, name)
  end
  if type(styles_path) == "string" then
    local relative = styles_path:gsub("^%./", ""):gsub("/+$", "")
    local inside = relative ~= ""
      and relative ~= "."
      and not relative:find("^[/~$]")
      and not ("/" .. relative .. "/"):find("/%.%./")
    if inside then
      table.insert(paths, relative)
    end
  end
  return paths
end

return M
